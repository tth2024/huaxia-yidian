// 根据卡牌名称查找文案
export function getAnecdoteByCardName(name: string): string | null {
  // 优先查找组合文案，否则查找单卡文案
  const a = FULL_ANECDOTES[name];
  if (a) return a.text;
  // 尝试匹配部分名称
  for (const key of Object.keys(FULL_ANECDOTES)) {
    if (key.includes(name) || name.includes(key)) {
      return FULL_ANECDOTES[key].text;
    }
  }
  return null;
}
